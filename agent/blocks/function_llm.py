from collections.abc import Callable
import json

from ._base import Block


class FunctionLLM(Block):
    """Use a model to select and execute one batch of tool calls.

    Args:
        model_runner: Model runner used to generate a tool decision.
        tools: Functions available to the model, identified by their names.
        extract_tool_calls: Parser that converts model output into a list of
            calls with `name` and `arguments` keys. Return an empty list when
            there are no calls, or raise an error for malformed output.
    """

    def __init__(
        self,
        model_runner: Block,
        tools: list[Callable],
        extract_tool_calls: Callable,
    ):
        assert callable(extract_tool_calls)
        # Components
        self.model_runner = model_runner
        self.tools = tools
        self.extract_tool_calls = extract_tool_calls

        # Tool registry
        self.tool_registry = {}
        for func in tools:
            name = func.__name__
            if name in self.tool_registry:
                raise ValueError(f"Duplicate tool name: {name}")
            self.tool_registry[name] = func

    def _extract_tool_calls(self, text: str) -> list:
        """Parse tool calls from the model's output."""
        assert callable(self.extract_tool_calls)
        tool_calls = self.extract_tool_calls(text)
        return tool_calls

    def _execute_tool(self, call: dict) -> dict:
        """Execute a tool and return a JSON-compatible success or error result."""
        # Execute and serialize
        try:
            func = self.tool_registry[call["name"]]
            arguments = call["arguments"]
            print(f"Running tool {call["name"]}")
            result = func(**arguments)
            data = json.loads(json.dumps(result, allow_nan=False))
            return {"ok": True, "data": data}
        except Exception as error:
            # Error result
            return {
                "ok": False,
                "error": {"type": type(error).__name__, "message": str(error)},
            }

    def run(
        self,
        prompt: str | list,
        *,
        max_new_tokens: int = 512,
        temperature: float | None = None,
    ) -> dict:
        """Select and execute tool calls for a prompt or conversation.

        Args:
            prompt: User text or a list of chat messages owned by the caller.
            max_new_tokens: Maximum number of tokens generated by the model.
            temperature: Sampling temperature, or None to use the runner default.

        Returns:
            A dictionary with the raw model output, a list of tool calls and
            their results, and an error if parsing failed. Tool execution errors
            are returned in the result of the corresponding call.
        """
        # Messages
        if isinstance(prompt, str):
            messages = [{"role": "user", "content": prompt}]
        elif isinstance(prompt, list):
            assert prompt, "message history must not be empty"
            # NOTE: make a shallow copy
            messages = list(prompt)
        else:
            raise TypeError(f"Not supported: prompt {type(prompt)}")

        # Configurations
        options = {"max_new_tokens": max_new_tokens}
        if temperature is not None:
            options["temperature"] = temperature
        options["tools"] = self.tools

        # Model run
        response = self.model_runner.run(messages, **options)

        # Parse tool calls
        outputs = {"raw": response, "tool_calls": [], "error": None}
        try:
            tool_calls = self._extract_tool_calls(text=response)
        except Exception as error:
            outputs["error"] = {"type": type(error).__name__, "message": str(error)}
            return outputs

        if not tool_calls:
            return outputs

        # Execute a tool
        tool_results = []
        for call in tool_calls:
            result = self._execute_tool(call)
            tool_results.append({**call, "result": result})
        outputs["tool_calls"] = tool_results

        return outputs
